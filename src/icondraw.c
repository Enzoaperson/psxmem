int drawicon(unsigned char *icon, unsigned char *palette, short parms){
	unsigned char R8[17], G8[17], B8[17];
	unsigned short *colortable555 = (unsigned short *)palette;
	//printf("%x\n", colortable555[1]);
	
	//Convert the Color palette from RGB 555 to RGB 888
	for(char i = 0; i < 16; i++){
		R8[i] = (((colortable555[i] & 31) * 527) + 23) >> 6;
		G8[i] = ((((colortable555[i] >> 05) & 31) * 527) + 23) >> 6;
		B8[i] = ((((colortable555[i] >> 10) & 31) * 527) + 23) >> 6;
	}
	
	//Draw the actual Icon
	for(unsigned char i = 0; i < 128; i++){
		if(!(i % 8) && i){
			printf("\n");
		}
		unsigned char pixel1 = icon[i] & 0b00001111;
		unsigned char pixel2 = (icon[i] & 0b11110000) >> 4;
		printf("\e[7m\e[38;2;%d;%d;%dm  ", R8[pixel1], G8[pixel1], B8[pixel1]);
		printf("\e[7m\e[38;2;%d;%d;%dm  ", R8[pixel2], G8[pixel2], B8[pixel2]);
	}
	//Print the Color palette here if requested
	if(parms & PALETTE_SWITCH){
		printf("\n\n");
		for(unsigned char i = 0; i < 16; i++){
			printf("\e[7m\e[38;2;%d;%d;%dm  ", R8[i], G8[i], B8[i]);
		}
	}
	printf("\n");
	//while(1);
	//Return escape commands to normal
	printf("\e[0m");
}

